    public function run(): void
    {
        foreach ($this->conjuntos as $nombreMaterial => $piezas) {
            $materialId = DB::table('materiales')
                ->whereNull('servicio_id')
                ->where('nombre', $nombreMaterial)
                ->value('id');

            if (! $materialId) {
                $materialId = DB::table('materiales')->insertGetId([
                    'servicio_id' => null,
                    'nombre' => $nombreMaterial,
                    'activo' => 1,
                    'creado_en' => now(),
                ]);
            }

            foreach ($piezas as $pieza) {
                $instrumentoId = $this->instrumentoId($pieza['nombre'], $pieza['codigo']);

                $existe = DB::table('material_instrumentos')
                    ->where('material_id', $materialId)
                    ->where('instrumento_id', $instrumentoId)
                    ->exists();

                if (! $existe) {
                    DB::table('material_instrumentos')->insert([
                        'material_id' => $materialId,
                        'instrumento_id' => $instrumentoId,
                        'cantidad_predeterminada' => $pieza['cantidad'],
                        'created_at' => now(),
                        'updated_at' => now(),
                    ]);
                }
            }
        }
    }

    private function instrumentoId(string $nombre, ?string $codigo): int
    {
        $query = DB::table('instrumentos')->where('nombre', $nombre);

        $instrumentoId = $codigo === null
            ? $query->whereNull('codigo')->value('id')
            : $query->where('codigo', $codigo)->value('id');

        if ($instrumentoId) {
            return (int) $instrumentoId;
        }

        return (int) DB::table('instrumentos')->insertGetId([
            'nombre' => $nombre,
            'codigo' => $codigo,
            'activo' => 1,
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }
